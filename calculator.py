def compute_family_allowance(has_spouse: bool, num_children: int, num_other_dependents: int) -> int:
    """
    배우자(있으면) 40,000원
    자녀: 첫째 50,000 / 둘째 80,000 / 셋째 이후 120,000 (1인당)
    기타부양가족: 1인당 20,000원
    총 지급 대상 4인 이내
    """
    total_amount = 0
    total_count = 0

    if has_spouse and total_count < 4:
        total_amount += 40000
        total_count += 1

    child_rates = [50000, 80000, 120000]  # 첫째/둘째/셋째 이후
    children_left = num_children or 0
    child_index = 0
    while children_left > 0 and total_count < 4:
        rate = child_rates[child_index] if child_index < len(child_rates) else child_rates[-1]
        total_amount += rate
        total_count += 1
        children_left -= 1
        child_index += 1

    others_left = num_other_dependents or 0
    while others_left > 0 and total_count < 4:
        total_amount += 20000
        total_count += 1
        others_left -= 1

    return total_amount


def compute_pay_items(worker_row: dict) -> dict:
    """
    운영현황 한 사람 분의 데이터(worker_row)로 E~L열 지급항목을 계산한다.
    worker_row 필요 키:
      소정근로시간, 연차수당_지급일수, 시간외근무시간, 배우자여부, 자녀수, 기타부양가족수
    반환: {"기본급":.., "정액급식비":.., "정기상여금":.., "생활임금보전수당":..,
           "연차수당":.., "가족수당":.., "시간외근무수당":.., "기타수당": 0,
           "보수내역합계": ..}
    """
    hours = int(worker_row.get("소정근로시간"))
    table = SALARY_TABLE[hours]

    base_pay = table["기본급"]
    meal_allowance = table["정액급식비"]
    bonus = table["정기상여금"]
    living_wage_allowance = table["생활임금보전수당"]

    annual_leave_days = worker_row.get("연차수당_지급일수") or 0
    annual_leave_pay = int(annual_leave_days) * table["연차수당_일단가"]

    overtime_hours = worker_row.get("시간외근무시간") or 0
    overtime_pay = int(overtime_hours) * table["시간외근무수당_시간단가"]

    has_spouse = bool(worker_row.get("배우자여부"))
    num_children = int(worker_row.get("자녀수") or 0)
    num_other_dependents = int(worker_row.get("기타부양가족수") or 0)
    family_allowance = compute_family_allowance(has_spouse, num_children, num_other_dependents)

    etc_allowance = 0  # 기타수당(L열) - 별도 입력 데이터 없음, 0 고정

    total_pay = (base_pay + meal_allowance + bonus + living_wage_allowance
                 + annual_leave_pay + family_allowance + overtime_pay + etc_allowance)

    return {
        "기본급": base_pay,
        "정액급식비": meal_allowance,
        "정기상여금": bonus,
        "생활임금보전수당": living_wage_allowance,
        "연차수당": annual_leave_pay,
        "가족수당": family_allowance,
        "시간외근무수당": overtime_pay,
        "기타수당": etc_allowance,
        "보수내역합계": total_pay,
    }


def compute_taxable_monthly(pay_items: dict) -> int:
    """공제전 보수월액 = 보수내역합계 - min(정액급식비, 200000)"""
    total_pay = pay_items["보수내역합계"]
    meal_allowance = pay_items["정액급식비"]
    return total_pay - min(meal_allowance, MEAL_ALLOWANCE_NONTAX_LIMIT)
