def lookup_income_tax(taxable_monthly: int, name: str = "", messages: list = None) -> int:
    """
    taxable_monthly: 공제전 보수월액 (원 단위)
    반환: 소득세 (원 단위), 공제대상가족 수 1명 고정
          범위 초과 시 messages에 경고 남기고 0 반환
    """
    if messages is None:
        messages = []

    monthly_thousand = taxable_monthly // 1000
    if monthly_thousand < 770:
        return 0

    for (lower, upper, tax) in INCOME_TAX_TABLE_1:
        if lower <= monthly_thousand < upper:
            return tax

    msg = f"[{name}] 월급여액이 간이세액표 범위 초과 - 수동 확인 필요"
    messages.append(msg)
    print(msg)
    return 0


# ---------------------------------------------------------------------
# 일할계산 공통 함수
# ---------------------------------------------------------------------
def calc_prorate_ratio(
    hire_date: date,
    expire_date: date,
    target_year: int,
    target_month: int
) -> tuple:
    """
    일할계산 비율 산출 함수
    - hire_date    : 채용일 (운영현황 G열)
    - expire_date  : 계약만료일 (운영현황 H열)
    - target_year  : 계산 대상 연도
    - target_month : 계산 대상 월

    반환값: (ratio: float, work_days: int, total_days: int)
    - ratio = 0.0        → 보험료 0원 (전월 이전 상실)
    - ratio = 1.0        → 전액 부과 (말일 상실 또는 익월 이후 만료)
    - 0 < ratio < 1.0     → 일할계산
    """
    month_first    = date(target_year, target_month, 1)
    month_last_day = calendar.monthrange(target_year, target_month)[1]
    month_last     = date(target_year, target_month, month_last_day)

    # 1단계: 전월 이전 상실 → 0원
    if expire_date < month_first:
        return 0.0, 0, month_last_day

    # 2단계: 해당 월 도중 상실 → 일할계산
    if expire_date < month_last:
        work_start = max(hire_date, month_first)
        work_end   = expire_date
        work_days  = (work_end - work_start).days + 1
        total_days = month_last_day
        return work_days / total_days, work_days, total_days

    # 3단계: 해당 월 말일 또는 익월 이후 만료 → 전액 부과
    return 1.0, month_last_day, month_last_day


def apply_prorate(taxable_monthly: int, rate: float, hire_date: date, expire_date: date,
                   target_year: int, target_month: int) -> int:
    """
    calc_prorate_ratio 결과를 이용해 실제 보험료(원)를 계산한다.
    ratio == 0.0 -> 0
    ratio == 1.0 -> int(공제전보수월액 * 요율)
    0 < ratio < 1.0 -> int(공제전보수월액 * 요율 * ratio)
    """
    ratio, _, _ = calc_prorate_ratio(hire_date, expire_date, target_year, target_month)
    if ratio == 0.0:
        return 0
    if ratio == 1.0:
        return int(taxable_monthly * rate)
    return int(taxable_monthly * rate * ratio)


def is_age_65_or_older_at_hire(birth_date: date, hire_date: date) -> bool:
    """채용일 기준 만 65세 이상 여부 (만 65세 이상 새로이 취득한 자 판단용)"""
    if birth_date is None or hire_date is None:
        return False
    age = hire_date.year - birth_date.year - (
        (hire_date.month, hire_date.day) < (birth_date.month, birth_date.day)
    )
    return age >= 65


