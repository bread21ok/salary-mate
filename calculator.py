def calc_health_pension_charge(file_amount, hire_date: date, expire_date: date,
                                target_year: int, target_month: int) -> int:
    """
    당월 1일 취득      -> 당월 보험료 부과 (파일 값 그대로)
    당월 1일 상실      -> 당월 보험료 미부과 (0)
    당월 2일~말일 취득 -> 당월 보험료 미부과 (0)
    당월 2일~말일 상실 -> 당월 보험료 부과 (파일 값 그대로)
    그 외(당월 내내 재직)-> 파일 값 그대로
    파일 값이 0 또는 None -> 0
    """
    if not file_amount:
        return 0

    month_first = date(target_year, target_month, 1)
    month_last_day = calendar.monthrange(target_year, target_month)[1]
    month_last = date(target_year, target_month, month_last_day)

    acquired_this_month = hire_date is not None and month_first <= hire_date <= month_last
    lost_this_month = expire_date is not None and month_first <= expire_date <= month_last

    if acquired_this_month:
        return int(file_amount) if hire_date == month_first else 0
    if lost_this_month:
        return 0 if expire_date == month_first else int(file_amount)

    return int(file_amount)


